const assert=require('node:assert/strict');
const H=require('../digital_twin/sensor_identification/history.js');
const P=require('../digital_twin/joint_pressure.js');
const matrix=Array.from({length:112},(_,r)=>Array.from({length:17},(_,c)=>r+c));
const angles=[1000,800,600,400,200,0];
const text='index;angles;tactile_matrix;state\n7;'+JSON.stringify(angles)+';'+JSON.stringify(matrix)+';steady_state\n';
const rows=H.records(text);assert.equal(rows.length,1);
const packet=H.telemetry(rows[0],P.regions);
assert.deepEqual(packet.angles_act,angles);assert.equal(packet.index,'7');
assert.equal(Object.keys(packet.tactile_regions).length,17);
assert.equal(packet.tactile_regions.little_tip[0][0],0);
assert.equal(packet.tactile_regions.palm.length,8);
assert.equal(packet.tactile_regions.palm[7][13],127);
assert.deepEqual(H.numericArray('[1000 500 0 -1 1e2 nan]'),[1000,500,0,-1,100,null]);
assert.deepEqual(H.numericArray('[[1 2]\n [3 4]]'),[[1,2],[3,4]]);
assert.throws(()=>H.numericArray('[[1 ... 2]]'),/truncated/);
assert.throws(()=>H.numericArray('[1; process.exit()]'));
assert.throws(()=>H.telemetry({angles:'[1,2]',tactile_matrix:''},P.regions),/six valid/);
assert.throws(()=>H.telemetry({angles:JSON.stringify(angles),tactile_matrix:'[[1,2]]'},P.regions),/112/);
assert.deepEqual(H.telemetry({angles:JSON.stringify(angles),tactile_matrix:''},P.regions).tactile_regions,{});
const malformed=matrix.map(r=>r.slice());malformed[0][0]=null;
const partial=H.telemetry({angles:JSON.stringify(angles),tactile_matrix:JSON.stringify(malformed)},P.regions);
assert.equal(partial.tactile_regions.little_tip,undefined);
assert.ok(partial.tactile_regions.ring_tip);
const quoted='index;angles;tactile_matrix;state\r\n1;"[1000 800 600 400 200 0]";;"first\nsecond; \\"quoted\\""\r\n';
assert.equal(H.records('index;angles;state\n1;"[1 2 3 4 5 6]";"a\nb"')[0].state,'a\nb');
const comma='index,angles,state\n1,"[1000,800,600,400,200,0]",steady\n';
assert.deepEqual(H.telemetry(H.records(comma)[0],P.regions).angles_act,angles);
assert.throws(()=>H.records('angles;angles\n1;2'),/duplicate/);
assert.throws(()=>H.records('index;state\n1;steady'),/angles column/);
assert.throws(()=>H.records('angles;state\n"[1 2]'),/unfinished/);
console.log('PASS CSV delimiters, quoted fields, NumPy/JSON arrays, 112x17 mapping, missing pressure and invalid rows');
