const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=process.env.HAND_CHECKOUT||path.resolve(__dirname,'..');
const H=require(path.join(root,'digital_twin/sensor_identification/history.js')),R=H.runs;
const K=require(path.join(root,'digital_twin/joint_kinematics.js'));
const read=n=>JSON.parse(fs.readFileSync(path.join(root,'digital_twin',n),'utf8'));
const geometry=read('tactile_geometry.json'),profile=read('joint_geometry_profiles_for_codex.json').primary_profiles.rh56_tactile_toolkit_left;
const context={id:geometry.profile,profile,geometry,calibration:K.defaults(profile),boundaries:read('hand_boundaries.json')};
function row(index,bend,rotation=500,extra={}){
 const matrix=Array.from({length:112},()=>Array(17).fill(0));matrix[0][15]=700;
 return {index:String(index),state:'thumb_probing',slip_detected:'False',angles:JSON.stringify([1000,1000,1000,1000,bend,rotation]),tactile_matrix:JSON.stringify(matrix),...extra};
}
const rows=[row(1,800),row(2,20,300),row(3,20,700),row(4,0,500,{slip_detected:'True'}),row(5,0,500,{state:'resetting'}),row(6,100),row(7,100,300),row(8,20,700)];
const peak=R.build(rows,context,{pose_selection:'peak'});
assert.equal(peak.accumulation.pose_selection,'maximum_bend_per_thumb_rotation');
assert.deepEqual(peak.accumulation.selected_source_indices,['2','6','8']);
assert.equal(peak.accumulation.thumb_rotation_groups,3);
assert.deepEqual(peak.accumulation.selected_poses.map(p=>[p.thumb_rotation_raw,p.thumb_bend_raw]),[[300,20],[500,100],[700,20]]);
assert.equal(peak.accumulation.frames_reconstructed,3);
assert.equal(peak.accumulation.frames_total,8);
assert.equal(peak.accumulation.frames_skipped_pose,3);
assert.equal(peak.accumulation.frames_skipped_state,1);
assert.equal(peak.accumulation.frames_skipped_slip,1);
assert.deepEqual(peak.hand_snapshot.angles_act,JSON.parse(rows[7].angles));
assert(peak.points.every(p=>['2','6','8'].includes(p.source_index)));
assert(peak.boundary_points.every(p=>['2','6','8'].includes(p.source_index)));
assert(peak.boundary_points.some(p=>p.source_index==='2'));
assert(peak.boundary_points.some(p=>p.source_index==='8'));
const sweep=R.build(rows,context,{pose_selection:'all'});
assert.equal(sweep.accumulation.frames_reconstructed,6);
const reversed={...context,calibration:K.clone(context.calibration)};reversed.calibration.actuators.thumb_bend.reversed=true;
assert.deepEqual(R.build(rows,reversed,{pose_selection:'peak'}).accumulation.selected_source_indices,['1','7','8']);
const blank=JSON.stringify(Array.from({length:112},()=>Array(17).fill(0)));
const empty=R.build([row(1,900,500,{tactile_matrix:blank}),row(2,100,500,{tactile_matrix:blank}),row(3,400,650,{tactile_matrix:blank})],context,{pose_selection:'peak'});
assert.equal(empty.points.length,0);assert(empty.boundary_points.length>0);
assert.deepEqual(empty.accumulation.selected_source_indices,['2','3']);
assert.equal(empty.accumulation.frames_reconstructed,2);
assert.equal(R.validateFrame(empty).boundary_points.length,empty.boundary_points.length);
assert.throws(()=>R.build([row(1,1000),row(2,1001)],context),/six valid angles/);
assert.throws(()=>R.build(rows,context,{pose_selection:'invalid'}),/Unknown thumb pose/);
(async()=>{assert.deepEqual(await R.buildAsync(rows,context,{pose_selection:'peak'}),peak);console.log('PASS deepest bend per rotation, multiple-angle area, settled ties, slip/state exclusions, reversed calibration, no-pressure limits and sync/async parity');})().catch(e=>{console.error(e);process.exitCode=1});
